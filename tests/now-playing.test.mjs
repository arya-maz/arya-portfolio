import assert from 'node:assert/strict';
import { onRequestGet } from '../functions/api/now-playing.js';
const request = new Request('https://portfolio.test/api/now-playing');
const context = { env: { LASTFM_API_KEY:'test-key', LASTFM_USERNAME:'aryamaz' }, request, waitUntil: () => {} };
const realFetch = globalThis.fetch;
const sample = { name:'Test track', artist:{'#text':'Test artist'}, album:{'#text':'Test album'}, url:'https://www.last.fm/music/test', image:[{size:'small','#text':'https://example.com/small.jpg'},{size:'large','#text':'https://example.com/large.jpg'}] };
let calls=0;
globalThis.fetch=async () => { calls++; return Response.json({recenttracks:{track:[{...sample,'@attr':{nowplaying:'true'}}]}}); };
assert.equal((await onRequestGet({...context,env:{}})).status,503);
assert.equal(calls,0);
let data=await (await onRequestGet(context)).json();
assert.equal(data.status,'playing'); assert.equal(data.artwork,'https://example.com/large.jpg'); assert.ok(!JSON.stringify(data).includes('test-key'));
globalThis.fetch=async()=>Response.json({recenttracks:{track:[sample]}});
assert.equal((await (await onRequestGet(context)).json()).status,'recent');
globalThis.fetch=async()=>Response.json({recenttracks:{track:[]}});
assert.equal((await (await onRequestGet(context)).json()).status,'empty');
globalThis.fetch=async()=>Response.json({error:6,message:'upstream message contains test-key'});
let failure=await onRequestGet(context);assert.equal(failure.status,503);assert.ok(!(await failure.text()).includes('test-key'));
globalThis.fetch=async()=>{throw new Error('network failure test-key');};
assert.deepEqual(await (await onRequestGet(context)).json(),{status:'unavailable'});
