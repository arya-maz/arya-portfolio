data=await (await onRequestGet(context)).json();assert.equal(data.artwork,null);assert.equal(data.url,'https://www.last.fm/user/aryamaz');
const entries=new Map();const pending=[];
globalThis.caches={default:{match:async key=>entries.get(key.url)?.clone(),put:async(key,value)=>entries.set(key.url,value)}};
calls=0;globalThis.fetch=async()=>{calls++;return Response.json({recenttracks:{track:[sample]}});};
await onRequestGet({...context,waitUntil:p=>pending.push(p)});await Promise.all(pending);
await onRequestGet(context);assert.equal(calls,1);
delete globalThis.caches;globalThis.fetch=realFetch;
console.log('Passed: playing, recent, empty, missing config, API/network failures, safe URLs, secret redaction, edge-cache reuse.');
